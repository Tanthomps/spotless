/// `3725` → `"1:02:05"` (api.ts `formatEpisodeDuration`).
func formatEpisodeDuration(_ secs: Double) -> String {
    let t = Int(secs), h = t / 3600, m = t % 3600 / 60, s = t % 60
    return h > 0 ? String(format: "%d:%02d:%02d", h, m, s) : String(format: "%d:%02d", m, s)
}

/// Spotify's episode meta: "Mar 3 • 1 hr 12 min" / "23 min left".
func episodeLength(_ secs: Double) -> String {
    let m = Int((secs / 60).rounded())
    if m >= 60 { return m % 60 == 0 ? "\(m / 60) hr" : "\(m / 60) hr \(m % 60) min" }
    return "\(max(1, m)) min"
}

func episodeDate(_ unix: Double?, now: Date = Date()) -> String {
    guard let unix, unix > 0 else { return "" }
    let d = Date(timeIntervalSince1970: unix)
    let f = DateFormatter()
    f.locale = Locale(identifier: "en_US")
    f.dateFormat = Calendar.current.isDate(d, equalTo: now, toGranularity: .year) ? "MMM d" : "MMM d, yyyy"
    return f.string(from: d)
}

