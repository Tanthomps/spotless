/// api.ts `PodcastEpisode & { isNew }`: the episode's fields flattened next to `isNew`.
struct WhatsNewEpisode: Codable, Hashable, Identifiable {
    var episode: PodcastEpisode
    var isNew: Bool
    var id: String { episode.id }
    init(episode: PodcastEpisode, isNew: Bool) { self.episode = episode; self.isNew = isNew }
    private enum K: String, CodingKey { case isNew }
    init(from d: Decoder) throws {
        episode = try PodcastEpisode(from: d)
        isNew = try d.container(keyedBy: K.self).decode(Bool.self, forKey: .isNew)
    }
    func encode(to e: Encoder) throws {
        try episode.encode(to: e)
        var c = e.container(keyedBy: K.self)
        try c.encode(isNew, forKey: .isNew)
    }
}

