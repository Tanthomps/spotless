/// `downloads_retry` and `import_cancel` exist in `invoke.rs` but not on `CoreClient` (I-B's file):
/// these reach them through the real client's `call`, and give the mock the same behaviour. Should
/// the protocol gain the methods, these become their defaults and nothing else changes.
extension CoreClient {
    /// Every failed download goes back in the queue.
    func downloadsRetry() async throws {
        if let real = self as? RealCoreClient { _ = try await real.call("downloads_retry") }
    }

    /// Stops a running import (matches found so far stay remembered); a finished one is dropped.
    func importCancel() async throws {
        if let real = self as? RealCoreClient { _ = try await real.call("import_cancel"); return }
        if let mock = self as? MockCoreClient { mock.withLock { mock.fs.importSnap = nil } }
    }
}
