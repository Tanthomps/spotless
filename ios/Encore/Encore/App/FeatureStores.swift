// Observable stores for the feature streams (iOS counterparts of the desktop's
// `podcasts.svelte.ts`, `downloads/*.svelte.ts`, `audio.svelte.ts`, smart2 state). Views read these;
// every mutation goes through `CoreClient`, and core events keep them current (`AppModel.apply`).
import SwiftUI
import Observation

@MainActor @Observable
final class PodcastStore {
    let core: CoreClient
    var follows: [PodcastShow] = []
    var saved: [PodcastEpisode] = []
    var newEpisodes: [PodcastEpisode] = []
    var continueListening: [PodcastEpisode] = []
    /// Live progress from `podcasts:progress` (overrides what a page loaded).
    var progress: [String: EpisodeProgress] = [:]
    @ObservationIgnored let actions: CoreActions

    init(core: CoreClient) { self.core = core; actions = CoreActions(core: core) }

    /// The episode lists have answered once (until then they show placeholders, not "empty").
    var listsLoaded = false
    /// The first read of the episode lists failed (they show Try again instead of "empty").
    var listsFailed = false

    func refresh() async {
        // A failed read keeps what was there: an empty list would read as "you follow nothing".
        if let v = try? await core.podcastFollows() { follows = v }
        do { saved = try await core.podcastSavedEpisodes(); listsLoaded = true; listsFailed = false } catch {
            if !listsLoaded && !FriendlyError.isCancellation(error) { listsFailed = true }
        }
        if let v = try? await core.podcastNewEpisodes(limit: 20) { newEpisodes = v }
        if let v = try? await core.podcastContinueListening(limit: 10) { continueListening = v }
    }

    func progressOf(_ e: PodcastEpisode) -> EpisodeProgress { progress[e.id] ?? e.progress }

    // stream: chapters — per episode, loaded beside playback (never in its way).
    var chapters: [String: [PodcastChapter]] = [:]
    /// Episodes whose chapters YouTube generated (the chapters sheet says so).
    var chaptersAuto: Set<String> = []
    func loadChapters(_ id: String, duration: Double? = nil) async {
        guard chapters[id] == nil else { return }
        if let c = try? await core.podcastChapters(id: id, durationSecs: duration) {
            if c.autoGenerated == true { chaptersAuto.insert(id) }
            chapters[id] = c.chapters
        }
    }
    func isFollowed(_ id: String) -> Bool { follows.contains { $0.id == id } }
    func isSaved(_ e: PodcastEpisode) -> Bool { saved.contains { $0.id == e.id } }

    @discardableResult
    func toggleFollow(_ show: PodcastShow) -> Bool {
        let on = !isFollowed(show.id)
        let before = follows
        if on { var s = show; s.followed = true; follows.insert(s, at: 0) } else { follows.removeAll { $0.id == show.id } }
        actions.run("follow", on ? "Couldn't follow this show" : "Couldn't unfollow this show", revert: { [weak self] in self?.follows = before }) { [weak self, core] in
            try await core.podcastFollow(show, follow: on)
            await self?.refresh()
        }
        return on
    }

    @discardableResult
    func toggleSaved(_ e: PodcastEpisode) -> Bool {
        let on = !isSaved(e)
        let before = saved
        if on { saved.insert(e, at: 0) } else { saved.removeAll { $0.id == e.id } }
        actions.run("saveEpisode", "Couldn't update Your Episodes", revert: { [weak self] in self?.saved = before }) { [weak self, core] in
            try await core.podcastSaveEpisode(e, saved: on)
            await self?.refresh()
        }
        return on
    }

    func markPlayed(_ e: PodcastEpisode, _ played: Bool) {
        actions.run("markPlayed", "Couldn't update this episode") { [weak self, core] in
            let p = try await core.podcastMarkPlayed(id: e.id, played: played)
            self?.progress[e.id] = p
            await self?.refresh()
        }
    }

    /// The show sheet's "Mark all as played": true when every episode took it.
    func markAllPlayed(showId: String) async -> Bool {
        await actions.perform("markPlayed", "Couldn't mark the episodes as played") {
            let page = try await core.podcastShow(id: showId, sort: .newest)
            for e in page.episodes { progress[e.id] = try await core.podcastMarkPlayed(id: e.id, played: true) }
        }
    }
}

/// Download state of one collection, for the toggle/ring.
enum DownloadState: Equatable {
    case none
    case downloading(Double) // 0...1
    case done
    /// Nothing left in flight and some songs failed: the toggle offers Retry (`downloads_retry`).
    case failed(Int)
}

@MainActor @Observable
final class DownloadStore {
    let core: CoreClient
    var snapshot: DownloadsSnapshot = .empty
    var done: Set<String> = []
    var active: [String: DownloadProgress] = [:]
    @ObservationIgnored let actions: CoreActions

    init(core: CoreClient) { self.core = core; actions = CoreActions(core: core) }

    /// Called when `offline` flips (network lost or back, offline mode toggled), launch included.
    @ObservationIgnored var onOfflineChange: ((Bool) -> Void)?
    @ObservationIgnored private var lastOffline = false

    func refresh() async {
        guard let s = try? await core.downloadsSnapshot() else { return }
        snapshot = s
        done = Set(s.done)
        active = Dictionary(s.active.map { ($0.videoId, $0) }, uniquingKeysWith: { a, _ in a })
        noteOffline()
    }

    func setNetwork(_ n: DownloadNetwork) {
        snapshot.network = n
        noteOffline()
    }

    private func noteOffline() {
        guard offline != lastOffline else { return }
        lastOffline = offline
        onOfflineChange?(offline)
    }

    var offline: Bool { snapshot.network.offline }
    func isDownloaded(_ videoId: String) -> Bool { done.contains(videoId) }
    func isDownloading(_ videoId: String) -> Bool { active[videoId] != nil }
    /// Greyed rows while offline (Spotify: everything not downloaded).
    func unavailableOffline(_ videoId: String) -> Bool { offline && !done.contains(videoId) }

    func state(_ collectionId: String) -> DownloadState {
        guard let c = snapshot.collections.first(where: { $0.id == collectionId }) else { return .none }
        if c.total > 0 && c.done >= c.total { return .done }
        if c.failed > 0 && c.done + c.failed >= c.total { return .failed(c.failed) }
        // Finished tracks plus a share of the bytes in flight (downloads.md): only this one's own songs.
        let inflight = active.values
            .filter { $0.collections?.contains(collectionId) ?? true }
            .reduce(0.0) { $0 + ($1.total > 0 ? $1.done / $1.total : 0) }
        let f = c.total == 0 ? 0 : min(0.99, (Double(c.done) + min(inflight, 3) * 0.5) / Double(c.total))
        return .downloading(f)
    }

    /// Out of space: what stops this download (and the Storage page says the same).
    func storageFull(_ collectionId: String) -> Bool {
        snapshot.collections.first { $0.id == collectionId }?.storageFull == true
    }
    var anyStorageFull: Bool { snapshot.collections.contains { $0.storageFull == true } }

    func isCollectionDownloaded(_ id: String) -> Bool { snapshot.collections.contains { $0.id == id } }

    /// `then`: after the core took it (an episode is then in Your Episodes too).
    @discardableResult
    func add(_ c: DownloadCollection, songs: [SongItem]? = nil, then: (@MainActor () async -> Void)? = nil) -> Task<Bool, Never> {
        let before = snapshot.collections
        snapshot.collections.append(DownloadCollectionStatus(id: c.id, kind: c.kind, title: c.title, subtitle: c.subtitle, thumbnail: c.thumbnail,
                                                             total: songs?.count ?? 1, done: 0, failed: 0, bytes: 0, addedAt: Date().timeIntervalSince1970))
        return actions.run("download", "Couldn't download this", revert: { [weak self] in self?.snapshot.collections = before }) { [weak self, core] in
            try await core.downloadsAdd(c, songs: songs)
            await self?.refresh()
            await then?()
        }
    }

    func remove(_ id: String) {
        let before = snapshot.collections
        snapshot.collections.removeAll { $0.id == id }
        actions.run("download", "Couldn't remove the download", revert: { [weak self] in self?.snapshot.collections = before }) { [weak self, core] in
            try await core.downloadsRemove(id: id)
            await self?.refresh()
        }
    }

    @discardableResult
    func removeAll() -> Task<Bool, Never> {
        actions.run("download", "Couldn't remove your downloads") { [weak self, core] in
            try await core.downloadsRemoveAll()
            await self?.refresh()
        }
    }

    /// Songs that failed go back in the queue (`downloads_retry`, every failed song at once).
    @discardableResult
    func retry() -> Task<Bool, Never> {
        actions.run("download", "Couldn't retry the downloads") { [weak self, core] in
            try await core.downloadsRetry()
            await self?.refresh()
        }
    }

    /// Total failed songs (Settings › Storage can offer Retry with `DownloadsRetryRow`).
    var failedCount: Int { snapshot.failed }

    /// Why downloads in flight aren't moving (nil: they are), for the ring's paused look and label.
    var pausedReason: String? {
        let n = snapshot.network
        guard n.paused || (n.offline && snapshot.queued > 0) else { return nil }
        if !n.online || n.offline { return "Paused while offline" }
        if n.metered && !n.allowMetered { return "Waiting for Wi-Fi" }
        return "Paused"
    }

    /// `revert`: undo the switch the caller flipped optimistically if the core refuses.
    func set(_ patch: DownloadSettingsPatch, revert: (@MainActor () -> Void)? = nil) {
        actions.run("downloadSettings", "Couldn't change that setting", revert: revert) { [weak self, core] in
            let s = try await core.downloadsSetSettings(patch)
            guard let self else { return }
            self.snapshot = s; self.done = Set(s.done); self.noteOffline()
        }
    }
}

/// Audio, smart and app settings plus the sleep timer, playback speed, Smart Shuffle and What's New dot.
@MainActor @Observable
final class SettingsStore {
    let core: CoreClient
    var audio: AudioSettings?
    var eqInfo: EqInfo?
    var smart = SmartSettings(shuffleMode: "standard", explicitFilter: false, privateSession: false)
    var values: [String: String] = [:]
    var sleep: SleepState = .off
    var speed: Double = 1
    var smartShuffle: SmartShuffleState = .off
    var whatsNewCount = 0
    var madeForYou: [MfyCard] = []
    @ObservationIgnored let actions: CoreActions

    init(core: CoreClient) { self.core = core; actions = CoreActions(core: core) }

    func refresh() async {
        // A failed read keeps what was there (never blank switches that look like "off").
        if let a = try? await core.audioSettings() { audio = a; sleep = a.sleep }
        if eqInfo == nil { eqInfo = try? await core.eqInfo() }
        if let s = try? await core.smartSettings() { smart = s }
        if let v = try? await core.getSettings() { values = v }
        speed = Double(values[SettingKey.speed] ?? "") ?? 1
        if let s = try? await core.smartShuffleState() { smartShuffle = s }
        if let n = try? await core.whatsNew().newCount { whatsNewCount = n }
        if let m = try? await core.madeForYou() { madeForYou = m }
    }

    func bool(_ key: String, default d: Bool = false) -> Bool { values[key].map { $0 == "true" } ?? d }
    func string(_ key: String, default d: String = "") -> String { values[key] ?? d }

    /// Optimistic: the switch moves at once and moves back (with a toast) if the core refuses.
    @discardableResult
    func set(_ key: String, _ value: String) -> Task<Bool, Never> {
        let before = values[key]
        values[key] = value
        return actions.run("setting", "Couldn't save that setting", revert: { [weak self] in self?.values[key] = before }) { [core] in
            try await core.setSetting(key: key, value: value)
        }
    }
    @discardableResult
    func set(_ key: String, _ on: Bool) -> Task<Bool, Never> { set(key, on ? "true" : "false") }

    func setSmart(_ key: String, _ value: String) {
        let before = smart
        if key == "shuffle_mode" { smart.shuffleMode = value }
        if key == "explicit_filter" { smart.explicitFilter = value == "true" }
        actions.run("setting", "Couldn't save that setting", revert: { [weak self] in self?.smart = before }) { [core] in
            try await core.smartSetSetting(key: key, value: value)
        }
    }

    func setPrivateSession(_ on: Bool) {
        let before = smart.privateSession
        smart.privateSession = on
        actions.run("setting", on ? "Couldn't start a private session" : "Couldn't end the private session",
                    revert: { [weak self] in self?.smart.privateSession = before }) { [core] in try await core.setPrivateSession(on) }
    }

    /// Slider drags send many of these; only a committed change reports a failure (and snaps back).
    func setEq(enabled: Bool, gains: [Double], commit: Bool) {
        let g = gains.map(EQ.clamp)
        let before = audio?.eq
        audio?.eq = EqState(enabled: enabled, gains: g, preset: EQ.presetName(g), preamp: EQ.autoPreamp(g))
        let op: @MainActor () async throws -> Void = { [weak self, core] in
            let s = try await core.setEq(enabled: enabled, gains: g, commit: commit)
            self?.audio?.eq = s
        }
        if commit {
            actions.run("eq", "Couldn't change the equalizer", revert: { [weak self] in if let before { self?.audio?.eq = before } }, op)
        } else {
            Task { if let e = await actions.attempt("eq", op), !FriendlyError.isCancellation(e) { _ = friendlyError(e, "Couldn't change the equalizer") } }
        }
    }

    func setEqPreset(_ name: String) {
        actions.run("eq", "Couldn't change the equalizer") { [weak self, core] in
            let s = try await core.setEqPreset(name)
            self?.audio?.eq = s
        }
    }

    func setCrossfade(_ secs: Int) {
        let before = audio?.crossfadeSecs
        audio?.crossfadeSecs = secs
        actions.run("setting", "Couldn't change crossfade", revert: { [weak self] in if let before { self?.audio?.crossfadeSecs = before } }) { [core] in
            _ = try await core.setCrossfade(seconds: secs)
        }
    }

    func setNormalize(_ on: Bool) {
        let before = audio?.normalize
        audio?.normalize = on
        actions.run("setting", "Couldn't save that setting", revert: { [weak self] in if let before { self?.audio?.normalize = before } }) { [core] in
            try await core.setNormalize(on)
        }
    }
    func setLevel(_ l: VolumeLevel) {
        let before = audio?.level
        audio?.level = l
        actions.run("setting", "Couldn't save that setting", revert: { [weak self] in if let before { self?.audio?.level = before } }) { [core] in
            try await core.setVolumeLevel(l)
        }
    }

    func setSleep(minutes: Int?, endOfTrack: Bool = false) {
        actions.run("sleep", "Couldn't set the sleep timer") { [weak self, core] in
            let s = try await core.setSleepTimer(minutes: minutes, endOfTrack: endOfTrack)
            self?.sleep = s
        }
    }
    func cancelSleep() {
        actions.run("sleep", "Couldn't turn off the sleep timer") { [weak self, core] in
            let s = try await core.cancelSleepTimer()
            self?.sleep = s
        }
    }

    /// The podcast speed: applied now and remembered (`episode_speed`) for the next episode and launch.
    func setSpeed(_ r: Double) {
        let before = (speed, values[SettingKey.speed])
        speed = r
        values[SettingKey.speed] = String(r)
        actions.run("speed", "Couldn't change the speed", revert: { [weak self] in self?.speed = before.0; self?.values[SettingKey.speed] = before.1 }) { [core] in
            try await core.setSpeed(r)
            try await core.setSetting(key: SettingKey.speed, value: String(r))
        }
    }

    /// Returns false when Smart Shuffle isn't available here (not an own playlist).
    func setSmartShuffle(_ on: Bool) async -> Bool {
        do { smartShuffle = try await core.smartShuffleSet(on); return true } catch { return false }
    }
}

