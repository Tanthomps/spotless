/// Index of the chapter playing at `pos` (the last one started), -1 before the first. Same rule as
/// `chapterAt` in ui/src/lib/chapters.ts.
func chapterAt(_ list: [PodcastChapter], _ pos: Double) -> Int {
    list.lastIndex { $0.startSecs <= pos + 0.25 } ?? -1
}

/// stream: chapters. Chapter starts are soft detents on the scrubber, never magnets: the thumb
/// follows the finger, damped for a few points either side of a start (`chapterDetent`), a
/// selection tick marks each start it crosses, and only a slow release a few points from a start
/// settles onto it (`chapterSettle`). Distances are on screen (points), not a share of the
/// episode. Same release rule as `settleOnRelease` in ui/src/lib/scrub.ts; per frame of a drag,
/// so it stays in the UI like `chapterAt`.
enum ChapterDetent {
    /// Points either side of a start where the thumb is damped (shrunk where starts are closer).
    static let zone = 12.0
    /// The thumb moves at 1 - damping of the finger's speed right at a start, back to 1:1 at the
    /// zone's edge (C1-smooth, so there is no felt edge).
    static let damping = 0.85
    /// A release this close to a start (points) settles onto it...
    static let settleRadius = 7.0
    /// ...only when the finger was this slow (points / s) as it lifted: flicks land where they land.
    static let settleMaxSpeed = 150.0
}

/// Starts strictly inside the episode (the marks on the bar), ascending.
private func chapterBoundaries(_ list: [PodcastChapter], _ duration: Double) -> [Double] {
    list.map(\.startSecs).filter { $0 > 0 && $0 < duration }.sorted()
}

/// Where the thumb shows for the finger at `pos` (seconds) on a bar `width` points long: within
/// `ChapterDetent.zone` of a start, finger offset r maps to r·(1 − k(1 − |r|/z)²) — slow at the
/// start, catching up smoothly by the zone's edge, so it can rest on a start but drags through it.
func chapterDetent(_ list: [PodcastChapter], _ pos: Double, duration: Double, width: Double) -> Double {
    guard duration > 0, width > 0 else { return pos }
    let b = chapterBoundaries(list, duration)
    guard let i = b.indices.min(by: { abs(b[$0] - pos) < abs(b[$1] - pos) }) else { return pos }
    let ppS = width / duration
    // Half the gap to a neighbour at most: two zones never overlap, so the mapping stays continuous.
    var z = ChapterDetent.zone
    if i > 0 { z = min(z, (b[i] - b[i - 1]) * ppS / 2) }
    if i < b.count - 1 { z = min(z, (b[i + 1] - b[i]) * ppS / 2) }
    let r = (pos - b[i]) * ppS
    guard z > 0, abs(r) < z else { return pos }
    let u = 1 - abs(r) / z
    return b[i] + r * (1 - ChapterDetent.damping * u * u) / ppS
}

/// Where a drag released at `pos` (seconds) lands: the nearest start when it is within
/// `ChapterDetent.settleRadius` points and the finger moved under `settleMaxSpeed` points / s;
/// otherwise exactly `pos`.
func chapterSettle(_ list: [PodcastChapter], _ pos: Double, duration: Double, width: Double, speed: Double) -> Double {
    guard duration > 0, width > 0, abs(speed) <= ChapterDetent.settleMaxSpeed else { return pos }
    guard let n = chapterBoundaries(list, duration).min(by: { abs($0 - pos) < abs($1 - pos) }),
          abs(n - pos) * width / duration <= ChapterDetent.settleRadius else { return pos }
    return n
}

/// The finger's speed as it lifted (units / s), from drag samples (x, time) in order: over the
/// last 0.1 s of movement, 0 when it had rested 0.08 s before lifting at `end`.
func releaseSpeed(_ samples: [(x: Double, t: Double)], end: Double) -> Double {
    guard let last = samples.last, end - last.t < 0.08 else { return 0 }
    guard let first = samples.last(where: { last.t - $0.t >= 0.1 }) ?? samples.first, last.t > first.t else { return 0 }
    return abs(last.x - first.x) / (last.t - first.t)
}

